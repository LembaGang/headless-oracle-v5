#!/usr/bin/env node
// B-482: writes src/chirindo-npm-version.ts from the registry's dist-tags.latest, so the
// version the agent files state is never typed. --check: exit 1 if the file is not the
// registry's latest. Exit 2: registry unreadable.
import { readFileSync, writeFileSync } from 'node:fs';

const REGISTRY = 'https://registry.npmjs.org/@headlessoracle%2fchirindo';
const FILE = new URL('../src/chirindo-npm-version.ts', import.meta.url);

async function main() {
	let latest;
	try {
		const res = await fetch(REGISTRY, { headers: { accept: 'application/json' } });
		if (!res.ok) throw new Error(`HTTP ${res.status}`);
		latest = (await res.json())['dist-tags']?.latest;
	} catch (e) {
		console.log(`ERROR cannot read ${REGISTRY}: ${e.message}`);
		return 2;
	}
	if (typeof latest !== 'string' || !/^\d+\.\d+\.\d+$/.test(latest)) {
		console.log(`ERROR dist-tags.latest is not a plain version: ${JSON.stringify(latest)}`);
		return 2;
	}
	const body = `// Generated by scripts/sync-chirindo-npm-version.mjs from ${REGISTRY} (dist-tags.latest).\n// Do not edit by hand: rerun the script.\nexport const CHIRINDO_NPM_VERSION = '${latest}';\n`;
	if (!process.argv.includes('--check')) {
		writeFileSync(FILE, body);
		console.log(`WROTE src/chirindo-npm-version.ts: ${latest}`);
		return 0;
	}
	let current = '';
	try { current = readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing is stale */ }
	if (current === body) {
		console.log(`MATCH src/chirindo-npm-version.ts states ${latest}, the registry's latest`);
		return 0;
	}
	console.log(`STALE src/chirindo-npm-version.ts is not the registry's latest (${latest}): run node scripts/sync-chirindo-npm-version.mjs`);
	return 1;
}

process.exitCode = await main();
